-- ============================================================================
-- games.last_inning 실재 확인 (읽기 전용 — 이 파일은 스키마를 바꾸지 않는다)
--
-- 이 컬럼은 **사용자가 손으로 추가했다**(dev·prod 둘 다). 그래서 저장소에 추가 DDL 이 없고,
-- 이 파일도 ALTER 를 담지 않는다 — 목적은 배포 전에 "정말 있는가"를 눈으로 확인하는 것뿐이다.
--
-- 왜 확인이 필요한가: `Game.lastInning` 매핑이 생기면서 **경기를 읽는 모든 조회의 SELECT 절에
-- 이 컬럼이 들어간다.** 컬럼이 없는 환경에서는 이닝별 결산 조회(GET /rt/quizzes/submissions)뿐
-- 아니라 경기 목록·라인업 조회까지 `Unknown column 'last_inning'` 로 깨진다(ApiResponse 래퍼도
-- 못 타는 순수 500 — /today 의 game_id 컬럼 누락 때 실측된 것과 같은 실패 형태다).
--
-- ⚠ **prod quiz 앱은 ddl-auto=none 이라 quiz 배포만으로는 컬럼이 생기지 않는다.** 반면 user 앱은
--   update 라 기동하면 nullable 컬럼을 붙인다 — 즉 "user 를 띄우면 알아서 생긴다"에 기대지 말고
--   배포 순서와 무관하게 아래 Step 1 로 먼저 확인할 것.
--
-- 값의 성격: 그 경기가 몇 회에 끝났는지이며 채우는 주체는 py-collector 다(앱에 games 쓰기 경로
--   없음). 종료·무승부·노게임 취소 경기에 값이 있고 진행 중·예정 경기는 NULL 이다. **NULL 은
--   장애가 아니라 정상 입력**이고, 그때 결산 조회는 200 + 빈 이닝 배열이 된다.
-- ============================================================================


-- ============================================================================
-- Step 1. 컬럼이 있는가 — 1행이 나와야 한다
-- ============================================================================
SHOW COLUMNS FROM games WHERE Field = 'last_inning';

-- 1행  → 배포 가능. 참고로 Type 은 tinyint 를 기대한다(current_inning 과 같은 축이라 폭을 맞췄다).
--        엔티티는 값을 Integer 로 읽으므로 int 로 만들어져 있어도 동작에는 문제가 없다.
-- 0행  → **여기서 멈출 것.** 컬럼을 만든 사람에게 확인하고, 없으면 만들어야 한다
--        (이 파일은 일부러 ALTER 를 담지 않는다 — 스키마 변경은 이 작업의 범위 밖이다).


-- ============================================================================
-- Step 2. 값의 분포 — 배포를 막는 조건은 아니고, 빈 응답을 봤을 때의 판단 근거다
-- ============================================================================
SELECT gs.name AS status,
       COUNT(*)                                        AS games,
       SUM(g.last_inning IS NOT NULL)                  AS with_last_inning,
       MIN(g.last_inning)                              AS min_last_inning,
       MAX(g.last_inning)                              AS max_last_inning
FROM games g
JOIN game_statuses gs ON gs.id = g.game_status_id
GROUP BY gs.name;

-- 기대: 수집기가 아직 이 값을 안 채우면 with_last_inning 이 전부 0 이다. 그 경우 **종료 경기의
--       결산 조회가 200 + 빈 배열**로 나오는 것이 정상 동작이며(폴백 금지 — 내 기록의 최대
--       이닝으로 대체하지 않는다), 값이 채워지면 재조회만으로 정상화된다.
-- 범위 이상(1 미만 또는 11 초과)이 보이면 수집 이상이다 — 결산 화면의 이닝 축 길이가 그대로
--       그 값이 되므로 원천을 확인할 것(정규 9 + 연장 2 가 한도).


