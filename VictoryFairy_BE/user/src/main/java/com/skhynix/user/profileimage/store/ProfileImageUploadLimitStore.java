package com.skhynix.user.profileimage.store;

/**
 * 비인증 임시 업로드 한도의 저장 포트({@code EmailVerificationStore} 와 같은 구조 — 정책 판정은
 * 서비스가 하고 저장소는 세는 일만 한다).
 */
public interface ProfileImageUploadLimitStore {

    /**
     * 그 {@code appId} 의 누적 횟수를 1 증가시키고 <b>증가 후 값</b>을 돌려준다.
     *
     * <p>읽고 나서 더하는 대신 증가 결과로 판정하게 만든 이유는 동시 요청이다 — 두 요청이 각각 "지금
     * 9회"를 읽으면 둘 다 통과해 한도가 뚫린다.
     *
     * <p>세는 창은 <b>고정</b>이다: 키가 새로 만들어질 때만 TTL 을 걸고 이후 증가로는 갱신하지 않는다.
     */
    int increment(String appId);

    /**
     * 저장(S3)이 실패했을 때 그 {@code appId} 가 소모한 1회를 <b>되돌린다</b>.
     *
     * <p>증가를 저장보다 앞에 두는 순서는 그대로 두고 환불만 붙인 이유는 동시성이다 — "저장 성공 후
     * 증가"로 바꾸면 두 요청이 같은 창에서 나란히 통과해 한도가 뚫린다. 원자적 증가로 게이트를 잡는
     * 구조는 유지하되, 인프라 장애로 객체가 하나도 안 생긴 회차가 정상 사용자의 슬롯을 태우지 않게
     * 한다(S3 실패 10회로 슬롯 10개가 조용히 소모되는 것이 실측된 자리다).
     *
     * <p>환불 대상은 <b>저장 실패뿐</b>이다. 형식·크기·{@code appId} 위반은 증가보다 앞에서 걸리므로
     * 되돌릴 것이 없고, 한도 초과 거절은 의도적으로 환불하지 않는다(이미 넘긴 창의 값이 11, 12 로
     * 늘어도 판정은 같다).
     *
     * <p>구현은 두 가지를 반드시 지켜야 한다: <b>키가 있을 때만 감소</b>(없는 키에 {@code DECR} 를
     * 걸면 TTL 없는 영구 키가 {@code -1} 로 생겨 그 {@code appId} 가 사실상 무제한이 된다)와
     * <b>TTL 미변경</b>(고정 창 계약 — 창은 키가 새로 만들어질 때만 열린다). 창이 이미 만료된 뒤에
     * 도착한 환불은 아무 일도 하지 않는 것이 정답이다.
     */
    void refund(String appId);
}
