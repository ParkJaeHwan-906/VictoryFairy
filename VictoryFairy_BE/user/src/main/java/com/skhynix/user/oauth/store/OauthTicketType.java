package com.skhynix.user.oauth.store;

/**
 * 티켓 종류. 셋을 한 저장소에 넣고 타입으로 가르는 이유는 <b>티켓 바꿔치기</b> 때문이다 — 종류별로
 * 키 공간을 나눠 두면 "이 문자열이 어떤 티켓인지"를 조회 결과로 알 수 있어야 하는데, 한 공간에 넣고
 * 쓰는 쪽이 기대 타입을 명시하면 잘못된 단계의 티켓이 그 자리에서 거절된다.
 */
public enum OauthTicketType {

    /** 신규 계정을 만들 자격. 이메일과 그 검증 상태가 확정돼 실려 있다. */
    SIGNUP,

    /**
     * provider 가 <b>이메일을 준</b> 경우의 인증 티켓. 이메일이 티켓 안에 있고 본문 이메일은 무시된다 —
     * 받아들이는 순간 남의 계정 이메일로 코드를 보내는 우회로가 열린다.
     */
    LINK,

    /** provider 가 <b>이메일을 주지 않은</b> 경우의 인증 티켓. 이메일이 비어 있고 사용자가 채운다. */
    INPUT
}
