package com.skhynix.quiz.quiz.vote;

import java.util.List;
import java.util.Map;

/**
 * 퀴즈 보기별 투표 수 포트. 적재(제출 시 증가)와 서빙 시점 스냅샷 읽기를 함께 맡는다.
 *
 * <p>호출부가 Redis 를 직접 알지 않게 하려고 둔 경계다. 구현은 저장소 장애를 <b>삼켜야</b> 한다 —
 * 집계는 부가 기능이고 제출·서빙이 본류라, 실패가 호출자에게 전파돼 채점·포인트·응답을 되돌리면
 * 안 된다. 그래서 적재 메서드는 성공 여부를 반환하지 않고, 읽기 메서드는 실패를 예외가 아니라
 * <b>빈 결과</b>로 표현한다(호출부가 없는 값을 0 으로 채운다).
 *
 * <p>⚠ 여기서 말하는 <b>보기 번호는 {@code quiz_options.option} 값 그대로이며 0부터 시작한다</b>
 * (적재기가 후보 배열 인덱스를 그대로 넣고 정답도 {@code A→0} 으로 변환한다). 이름이 {@code optionNo}
 * 라 1부터라고 읽기 쉬운 자리이며, 1-based 로 넘기면 전 보기가 한 칸씩 어긋난다.
 */
public interface QuizVoteTally {

    /**
     * 한 표를 더한다. <b>제출 트랜잭션이 커밋된 뒤</b>에 부르는 것이 호출부의 계약이다 — 제출 경로는
     * 포인트 적립 때문에 계정 행 락을 쥐고 있어, 트랜잭션 안에서 부르면 락을 쥔 채 Redis 왕복을 한다.
     *
     * @param quizId   {@code quizzes.id}
     * @param optionNo 사용자가 고른 보기 번호(0-based)
     */
    void increment(long quizId, int optionNo);

    /**
     * 아직 표가 없는 보기를 0 으로 만든 <b>뒤</b> 그 문제들의 분포를 읽어 돌려준다.
     *
     * <p>초기화와 읽기를 한 메서드로 묶은 것이 이 포트의 핵심 계약이다 — {@code /today} 응답은
     * "아무도 안 고른 보기도 0"이어야 하는데, 그게 성립하려면 <b>초기화가 끝난 뒤에 읽어야</b> 한다.
     * 두 연산을 갈라 두면 호출부에서 순서가 뒤집힐 수 있고, <b>뒤집혀도 첫 서빙에서는 결과가 우연히
     * 같아 조용히 통과한다</b>(필드가 없어 0 으로 채워지므로). 그래서 순서를 구현 안에 가둔다.
     *
     * <p>초기화는 <b>이미 값이 있는 필드를 건드리지 않는다</b> — {@code /today} 는 같은 문제를 여러
     * 사용자가 반복해서 받는 경로라, 덮어쓰면 나중 호출자가 이미 쌓인 표를 0 으로 밀어 버린다.
     * 읽기는 값·TTL 을 바꾸지 않는다(초기화·TTL 설정 외의 쓰기 명령을 추가하지 않는다).
     *
     * <p>반환 맵은 <b>부분적일 수 있다</b>: 저장소 장애면 빈 맵, 키·필드가 없거나 값이 0 이상의 정수로
     * 해석되지 않으면 그 항목이 빠진다. 호출부는 빠진 자리를 0 으로 채워야 하며, 그래서 응답 스키마는
     * 장애 여부와 무관하게 항상 한 모양이다. 담긴 값은 언제나 0 이상이다.
     *
     * @param optionNosByQuizId 문제 id → 그 문제의 보기 번호(0-based) 목록
     * @return 문제 id → (보기 번호(0-based) → 투표 수). 읽지 못한 문제·보기는 키 자체가 없다
     */
    Map<Long, Map<Integer, Long>> initializeAndRead(Map<Long, List<Integer>> optionNosByQuizId);
}
