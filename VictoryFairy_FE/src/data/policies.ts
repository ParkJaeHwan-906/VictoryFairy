/**
 * 목록 한 줄. 원문이 앞머리를 굵게 쓴 줄("**사용자가 제공한 데이터:** …")만 `lead` 를 갖는다.
 */
export type PolicyListItem = string | { lead: string; text: string };

/**
 * 본문 한 덩어리.
 *
 * - `lead` — 문단 앞머리의 굵은 말("**연락 창구:** …"). 본문과 한 줄로 이어 그린다.
 * - `strong` — 문단 전체가 굵은 경우(시행일 안내 등).
 *
 * 문단 사이의 빈 줄은 덩어리를 나누는 것으로 대신하고 간격은 CSS 가 준다(`NoticeBlock` 과 같다).
 */
export type PolicyBlock =
  | { type: 'paragraph'; text: string; lead?: string; strong?: boolean }
  | { type: 'list'; items: readonly PolicyListItem[] };

/** 소제목 하나와 그 아래 덩어리들. 원문의 소제목(제2 제목) 단위다. */
export interface PolicySection {
  title: string;
  body: readonly PolicyBlock[];
}

export interface PolicyDocument {
  title: string;
  /** 시행일. `YYYY-MM-DD`. */
  effectiveDate: string;
  /** 첫 소제목 앞의 머리말. */
  intro: readonly PolicyBlock[];
  sections: readonly PolicySection[];
}

