/**
 * 캐릭터 꾸미기(character) 도메인 타입.
 *
 * 아바타에 입히는 아이템의 **상점 · 인벤토리 · 착용 상태**를 다룬다.
 * 보유 포인트(`MyProfile.point`)의 첫 소비처이기도 하다 — 적립은 퀴즈 보상이 소유하고
 * 이 도메인은 **차감만** 한다.
 *
 * 이 도메인 전체를 지배하는 계약 넷:
 * - **상점과 인벤토리가 같은 목록이다.** `GET /characters/items` 는 카탈로그 **전체**를
 *   돌려주고, 보유 여부는 `having` 으로만 구분된다. "안 산 것만" 주는 API 는 없다.
 * - **사는 것과 입는 것이 다르다.** 구매한 아이템은 `having: true, active: false` 로
 *   들어온다 — 입히려면 착용 토글을 한 번 더 보내야 한다.
 * - **착용은 부위(`itemType`)당 하나다.** 꺼진 아이템을 켜면 같은 부위의 켜져 있던
 *   아이템이 자동으로 꺼진다. 다른 부위는 영향이 없다.
 * - **이미지가 두 벌이다.** 아래 `CharacterItem.displayImg` 주석 참고.
 */

/* ------------------------------------------------------------------ *
 * 부위(itemType)
 * ------------------------------------------------------------------ */

/**
 * 아이템 부위.
 *
 * 🚨 **닫힌 집합이 아니다.** 현재는 `의상` · `모자` · `소품` 3종이지만 enum 이 아니라
 * DB 행이라 **코드 변경 없이 늘어날 수 있다.** 그래서 유니온이 아니라 `string` 이다 —
 * `switch` 로 3종을 나열하고 default 를 빼면 새 부위가 추가되는 날 화면이 조용히 깨진다.
 * 화면은 목록에 실제로 실려 온 부위를 그대로 순회해야 한다.
 */
export type CharacterItemType = string;

/**
 * 현재 시드 기준으로 존재하는 부위. **표시 순서·기본 그룹핑 편의용이며 검증용이 아니다.**
 * 여기 없는 부위가 와도 정상이므로 이 상수로 필터링하면 안 된다.
 */
export const CHARACTER_ITEM_TYPE = {
  CLOTH: '의상',
  HEAD: '모자',
  ACCESSORY: '소품',
} as const;

/* ------------------------------------------------------------------ *
 * 카탈로그 아이템 — GET /characters/items
 * ------------------------------------------------------------------ */

/**
 * `GET /characters/items` 의 `data[]`. 키는 정확히 7개다.
 *
 * 정렬은 **부위 → 아이템 id** 순이라 목록이 부위별로 묶여 나오고, 같은 요청은 언제나
 * 같은 순서다(현재 시드: id 1~11 의상, 12~17 모자, 18~23 소품).
 * 카탈로그가 비어 있어도 404 가 아니라 **빈 배열**이다.
 */
export interface CharacterItem {
  /** 아이템 PK. **구매 · 토글 요청의 `characterItemId` 가 이 값이다**(인벤토리 행 id 가 아니다). */
  id: number;
  /** 부위. 닫힌 집합이 아니다 — `CharacterItemType` 주석 참고. */
  itemType: CharacterItemType;
  /** 표시명. 유니폼은 구단명이 아니라 **색상명**이다(`화이트 블루 라인 유니폼`). */
  name: string;
  /**
   * **상점 진열용** 이미지 EP(`stores/...`, 80×80 단독). `profileImgUrl` 과 같은
   * 오브젝트 키라 화면에 쓰려면 `toAssetUrl()` 로 도메인을 붙인다.
   *
   * 🚨 **착용용이 아니다.** 캐릭터에 겹쳐 그릴 이미지는 `GET /users/me` 의
   * `characterItems[].imgUrl`(`items/...`, 160×200 캐릭터 정합)이다 — 같은 아이템이지만
   * 좌표계가 다른 **별개 파일**이라 바꿔 쓰면 그림이 어긋난다.
   */
  displayImg: string;
  /** 구매 가격(포인트). 현재는 전 아이템 100 이지만 값으로 다뤄야 한다. */
  price: number;
  /** 이 계정이 **보유**했는가. 아이템은 영구적으로 한 개만 살 수 있다(재구매는 409). */
  having: boolean;
  /** 이 계정이 **착용 중**인가. `having: false` 면 언제나 `false`. */
  active: boolean;
}

/* ------------------------------------------------------------------ *
 * 착용 중인 아이템 — GET /users/me 의 characterItems[]
 * ------------------------------------------------------------------ */

/**
 * `GET /users/me` 의 `characterItems[]` — **지금 켜져 있는** 아이템만 실린다.
 * 키는 정확히 2개다.
 *
 * 🖼️ 여기 실린 이미지가 **캐릭터에 겹쳐 그릴 착용용**(160×200, 캐릭터 정합)이다.
 * **부위 순으로 정렬돼 오므로 받은 순서 그대로 겹쳐 그리면 된다** — 화면이 부위별
 * z-index 를 따로 정할 필요가 없고, 정해서도 안 된다(새 부위가 추가되는 날 어긋난다).
 *
 * 🚨 **`id` 가 없다 — 카탈로그와 id 로 이어 붙일 수 없다.** 두 목록을 잇는 유일한 키는
 * `itemType` 이고, 그마저 부위당 하나라는 규칙에 기대는 것뿐이다. 그래서 역할이 갈린다:
 * - "무엇을 입고 있나"(어느 카드에 체크를 켤지)는 카탈로그의 `active` 로 판단한다.
 * - "어떻게 그리나"(겹쳐 그릴 그림)는 이 목록으로만 할 수 있다 — 카탈로그의
 *   `displayImg` 로 아바타를 조립하면 좌표계가 달라 어긋난다.
 */
export interface WornCharacterItem {
  /** 부위. 닫힌 집합이 아니다 — `CharacterItemType` 주석 참고. */
  itemType: CharacterItemType;
  /**
   * **착용용** 이미지 EP(160×200, `items/...`). `toAssetUrl()` 로 도메인을 붙여 쓴다.
   * 상점의 `displayImg`(`stores/...`)와는 **경로 접두사부터 다른 별개 파일**이라
   * 바꿔 쓰면 그림이 어긋난다.
   */
  imgUrl: string;
}

/* ------------------------------------------------------------------ *
 * 요청 DTO — 구매 · 착용 토글이 같은 형태를 쓴다
 * ------------------------------------------------------------------ */

/**
 * `POST /characters/items/purchase` · `PUT /characters/items/active` 의 본문.
 *
 * 두 엔드포인트의 본문이 **완전히 같다**. 값은 카탈로그의 `data[].id` 이며
 * 인벤토리 행 id 가 아니다. 누락하면 서비스가 호출되기 전에 400 이다.
 */
export interface CharacterItemRequest {
  characterItemId: number;
}

/* ------------------------------------------------------------------ *
 * 응답 DTO
 * ------------------------------------------------------------------ */

/** `POST /characters/items/purchase` 의 `data`. */
export interface CharacterItemPurchaseResult {
  /** 방금 구매한 아이템 PK. */
  characterItemId: number;
  /**
   * **차감 후** 잔액. `GET /users/me` 를 다시 부르지 않아도 되도록 함께 준다 —
   * 화면·스토어의 포인트를 이 값으로 갱신하면 된다.
   */
  remainingPoint: number;
}

/** `PUT /characters/items/active` 의 `data`. */
export interface CharacterItemActiveResult {
  /** 요청한 아이템 PK. */
  characterItemId: number;
  /**
   * **요청 후의 상태**. `true` 면 지금 착용 중이다.
   *
   * PUT 이지만 멱등이 아니라 같은 요청을 두 번 보내면 켜졌다 꺼진다 —
   * 요청 횟수를 세지 말고 언제나 이 값으로 결과 상태를 판단한다.
   *
   * ⚠️ **같은 부위에서 대신 꺼진 아이템은 응답에 실리지 않는다.**
   * 로컬 목록을 직접 맞추려면 `applyCharacterItemToggle()` 을 쓴다.
   */
  active: boolean;
}
