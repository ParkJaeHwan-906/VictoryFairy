/**
 * 구단 내 BQ 순위.
 *
 * 세 경로(`GET /rankings/bq/top` · `GET /rankings/bq` · `GET /rankings/bq/me`)가
 * **모두 같은 항목 모양**을 쓴다 — 앞의 둘은 이 객체의 배열, 마지막은 객체 하나다.
 * 그래서 시상대와 목록과 "내 순위" 줄이 한 타입을 나눠 쓴다(docs/ranking.md).
 *
 * ── 없는 키를 기대하지 않는다 ──────────────────────────────────────────
 * 문서가 "`data` 의 키는 정확히 이 4개"라고 못박았다. `id` · `uid` · `isMe` · `email` ·
 * `point` · `quizAccuracy` 는 응답 어디에도 없다. 특히 두 가지가 화면에 영향을 준다.
 *
 * 1. **식별자가 없다.** 목록 key 로 쓸 고정값이 없고, `nickname` 은 UNIQUE 제약이
 *    없어 중복될 수 있으며, `rank` 도 동점이면 겹친다(1·1·3 방식). 목록의 key 는
 *    배열 인덱스로 잡을 수밖에 없다 — 정렬만 바뀌는 갱신이 없어 문제가 되지 않는다.
 * 2. **본인 표시가 없다.** TOP 10 안에 내가 있어도 다른 항목과 완전히 같은 모양으로
 *    올 뿐이라, 목록만 보고 어느 줄이 나인지 가릴 수 없다. 그래서 화면은 "내 순위"를
 *    목록에서 찾지 않고 `/rankings/bq/me` 로 따로 받는다.
 * ──────────────────────────────────────────────────────────────────────
 */
export interface BqRankingEntry {
  /** 1 이상 정수. 동점은 같은 값을 받고 다음 순위는 동점자 수만큼 건너뛴다(1·1·3). */
  rank: number;
  /**
   * 프로필 이미지 EP(BaseURL 을 뺀 오브젝트 키). 이미지가 없으면 `null`.
   *
   * ⚠️ **값이 있어도 파일이 있다는 뜻은 아니다.** 서버는 실존을 확인하지 않는다 —
   * 탈퇴 계정의 이미지는 S3 에서 지워지지만 컬럼 값은 그대로 남는다. 그래서 화면은
   * `null` 뿐 아니라 **로드 실패까지** 기본 이미지로 받아야 한다(docs/ranking.md).
   */
  profileImgUrl: string | null;
  /** 계정 닉네임 현재 값. UNIQUE 제약이 없어 중복될 수 있다. */
  nickname: string;
  /**
   * 누적 BQ 점수. 적립 누적치라 캐릭터 구매로 줄어드는 보유 포인트(`point`)와 다르다 —
   * 순위 축은 이 값 하나뿐이다. 누적 행이 없는 계정은 `0`.
   */
  bqScore: number;
}
