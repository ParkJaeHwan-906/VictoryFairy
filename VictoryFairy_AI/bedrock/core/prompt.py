"""판정 프롬프트 문안 + 응답 스키마 지시.

⚠️ **프롬프트 문안은 `accuracy-tuner` 소관이다**(요구사항 "범위 - 제외").
이 파일이 계약으로 고정하는 것은 다음 넷이다:

1. **출력 JSON 스키마** — 파서(`core/parser.py`)가 이 형태로만 파싱한다(BRK-LLM-11).
2. **축 식별자 3개** — `abuse`·`spam`·`offtopic` 외 값 금지(BRK-LLM-1b/11b).
3. **`offtopic` 은 본문 단위에만**(BRK-LLM-19).
4. **두 축이 겹치면 `abuse` 우선**(BRK-LLM-1c) — **코드로는 강제할 수 없다.** 응답
   스키마가 축을 하나만 담아 "겹침" 자체가 관측되지 않기 때문이다. 즉 **이 파일의
   문안이 BRK-LLM-1c 의 유일한 보장 지점**이고, 그 값이 폐기 범위까지 결정한다
   (본문이 `abuse` 면 게시글 전체 fail — PIPE-2SB-11b).

문안을 고치면 `PROMPT_VERSION` 을 **반드시 함께 올린다**. 이 값이 폐기 판정 결과에
실려 나가고(BRK-LLM-18) `accuracy-tuner` 가 과거 산출물을 구간으로 갈라 측정하는
근거가 된다 — 버전을 안 올리면 서로 다른 기준의 판정이 한 구간에 섞인다.

⚠️ **본문의 예문은 전부 잠정이다**(요구사항 "판정 요구사항" 경고). 실제로 패턴
검열을 통과하는 문장인지 확인되지 않았고, `test-data` 가 실표본
(`validation/pattern/success/`)에서 확정한다(BRK-LLM-47). 그래서 문안은 **예문이
아니라 케이스 클래스**를 판정 기준으로 쓰고 있다 — 예문을 갈아 끼워도 기준이
흔들리지 않게 하려는 구조다. **예문 교체는 문안 수정이므로 버전을 올린다.**
"""

