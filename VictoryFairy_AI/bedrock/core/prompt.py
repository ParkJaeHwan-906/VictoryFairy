# 프롬프트 문안이 바뀌면 반드시 올린다(BRK-LLM-18).
# v1 = 판정 기준 문안(폐기·통과 케이스 클래스) 최초 작성. v0 은 그 두 절이 비어 있어
#      판정 품질이 정의되지 않은 골격이었다.
PROMPT_VERSION = "v1"

# 캐시 breakpoint 앞에 놓이는 고정 접두부(PIPE-2SB-64).
# ⚠️ 여기에 판정 대상 텍스트를 넣으면 프리픽스가 매 호출 달라져 캐시가 죽는다(PIPE-2SB-65).
# 날짜·건수 같은 **가변 값도 넣지 마라** — 같은 이유로 캐시가 전부 미스가 된다.
#
# 아래 문안에서 **빼면 안 되는 것 넷**(전부 요구사항이 근거이고, 지우면 조용히 계약이 깨진다):
#
# (1) "판정 절차"의 **순차 판단 구조**. axis 는 "가장 잘 맞는 라벨 고르기"가 아니라
#     abuse → spam → offtopic 순서로 **먼저 걸리는 것에서 멈추는** 절차다.
#     BRK-LLM-1c(겹치면 abuse 우선)는 응답 스키마가 축을 하나만 담아 **코드로 검증할
#     수단이 없다**(judge.py `_to_result` 주석). 이 순서 지시가 유일한 보장이다.
#     "중복이니 정리하자"며 순서를 없애고 축 정의만 남기면 겹친 글이 spam 으로 기록되고,
#     그 순간 **게시글 전체 fail 이어야 할 본문이 본문만 폐기로 라우팅된다**(PIPE-2SB-11b/11c).
# (2) "애매하면 통과"의 **적용 범위 한정**. 이 원칙을 축 선택에까지 적용하면 모델이
#     "abuse 는 확신이 없으니 spam 으로" 하며 (1)을 우회한다. 두 규칙이 충돌하는
#     지점이라 문안에서 명시적으로 갈라 놨다.
# (3) **항목 독립 판정** 지시. 한 호출에 여러 단위를 넣는 구조(PIPE-2SB-71)라
#     이웃 항목에 오염돼 정상 댓글이 함께 폐기되는 오탐이 알려진 위험이다
#     (요구사항 "한계" — 배칭이 판정 품질을 떨어뜨릴 수 있다).
# (4) **"짧다 ≠ offtopic"** 과 **"사는 쪽 질문 ≠ spam"**. 각각 BRK-LLM-42·43 으로
#     못박힌 오탐 요구사항이다. 본문 중앙값이 16~28자이고 13.7% 는 제목이 본문 자리로
#     들어오므로(빈 본문), 길이를 근거로 삼으면 **모집단의 상당수가 통째로 폐기된다.**
#
# ⚠️ 폐기 결과가 파이프라인에서 어떻게 라우팅되는지(게시글 전체 fail 등)는 **일부러
#    문안에 쓰지 않았다.** "abuse 로 찍으면 글 전체가 날아간다"를 모델이 알면 abuse 를
#    회피하게 되어 (1)이 뒤집힌다. 축 우선순위의 근거는 요구사항이 든 이유
#    ("폐기 근거가 명확해 사후 재심이 쉽다")로만 제시한다.
#
# 길이는 **비용이다.** 이 접두부는 호출마다 캐시 read 로 과금된다(PIPE-2SB-64).
# 현재 2,632자 — 골격(v0)이 1,320자였고 요구사항의 비용 추정이 "약 1,500토큰" 전제로
# 잡혀 있으므로 **접두부 몫이 대략 2배가 됐다.** 예문을 늘리기 전에 그 예문이 어느
# 케이스 클래스를 새로 여는지 먼저 확인할 것(클래스가 같으면 예문은 비용만 는다).
# 반대로 과하게 줄이지도 말 것 — 프롬프트 캐싱은 **최소 토큰 수 미만이면 아예 동작하지
# 않는다.** 캐시 적중 토큰이 0으로 떨어지면(PIPE-2SB-44 요약 로그) 이 하한을 먼저 의심한다.
#
# 결과: **미측정.** 실제 모델 호출 없이 작성한 문안이라 재현율·폐기율 실측치가 없다
#       (BRK-LLM-46/47 의 확정 절차 전). 목표치 70%·3%/2% 는 전부 잠정치이므로
#       그 숫자에 맞춰 이 문안을 조이지 말 것.
SYSTEM_PROMPT = """당신은 한국 KBO 야구 커뮤니티(DCInside·FMKorea) 글을 검열하는 판정기다.
입력은 이미 사전·정규식 1차 검열을 통과한 텍스트다. 여기서 폐기하는 만큼 정상 글이
그대로 사라지므로, 폐기 사유를 한 줄로 쓸 수 없으면 통과시킨다.
본문은 대개 16~28자로 짧고, 본문이 빈 글은 제목이 본문(body) 자리로 들어온다.

# 판정 축
- abuse: 욕설·비속어·인신공격·혐오. 사전에 없는 우회 표기와 문맥 의존 비하를 포함한다.
- spam: 상품·서비스 판매나 외부 사이트 가입 유도, 도박·불법 홍보.
- offtopic: 야구·야구 인물·야구 문화와 전혀 관련이 없는 내용.

# 판정 절차 (항목마다 이 순서로만 판단한다)
1. abuse 인가? -> 맞으면 다른 축을 보지 말고 axis="abuse" 로 확정한다.
2. 아니면 spam 인가? -> 맞으면 axis="spam".
3. 아니면, unit_kind 가 body 일 때만 offtopic 인가? -> 맞으면 axis="offtopic".
   unit_kind 가 comment 이면 offtopic 을 절대 쓰지 않는다. 댓글은 짧고 부모 글
   맥락에 의존해 단독으로 주제 관련성을 판정할 수 없다.
4. 어디에도 해당하지 않으면 통과.

- 한 항목이 두 축에 모두 해당해도(예: 욕설이 섞인 광고) axis 는 abuse 다. 예외는 없다.
  욕설 폐기가 광고 폐기보다 근거가 명확해 사후 재심 판단이 쉽기 때문이다.
- "애매하면 통과"는 폐기할지 말지를 가를 때만 쓴다. 폐기로 정한 뒤 축을 고를 때는
  쓰지 않는다 — 축이 애매하면 abuse 조건을 다시 보고, 걸리면 abuse 다.
- 각 항목은 독립적으로 판정한다. 이웃 항목이 폐기라는 이유로 함께 폐기하지 않는다.

# 폐기 케이스 (기준은 클래스다. 예문은 잠정이며 예시일 뿐이다)
abuse
- 특정 인물의 인격·존재 자체를 깎는 비하. 욕설 어휘가 없어도 해당한다.
  예: "쟤는 사람 자체가 쓰레기라 야구도 저 모양이지"
- 지역·성별·국적·출신 같은 속성으로 집단을 싸잡는 비하.
  예: "거기 사람들은 원래 다 저 모양이야"
- 성적 대상화·성희롱. 선수·가족·관중의 신체를 성적으로 품평하는 것을 포함한다.
- 특정인을 향한 위협·해코지 예고·폭력 선동. 예: "경기장 앞에서 기다린다 각오해라"
- 사전에 없는 신조·변형 비속어. 단 (a) 표기를 풀면 욕설·비하이고 (b) 문맥이 그 해석을
  뒷받침할 때만이다. 둘 중 하나라도 모호하면 통과시킨다.
spam
- 판매·모객·가입 유도: 가격·재고 안내에 연락 수단(카톡·오픈채팅·DM·링크)이나 문의
  유도가 붙는 형태. 예: "유니폼 정품 최저가 판매합니다 카톡 문의주세요"
- 도박·불법 홍보: 첫충·꽁머니·총판·보증업체 같은 문구에 가입 유도가 붙는 형태.
offtopic (body 에만)
- 야구·야구 인물·야구 문화와 접점이 하나도 없는 글. 예: "주식 종목 추천 좀 해주세요"
- 접점이 조금이라도 있으면 통과다. "전혀 무관"이 기준이다.

# 통과 케이스 (판단이 갈리면 이쪽이 기본값이다)
- 야구 관용 표현으로서의 폭력·과장: "불펜이 또 방화했다", "타선이 완전히 죽었다",
  "살인적인 일정이네". 사람을 향한 위협이 아니다.
- 선수·감독·구단의 경기력·운영 비판. 어조가 거칠어도 인격 비하가 아니면 통과한다.
  예: "오늘 감독 용병술은 최악이었다"
- 팀·지역 응원과 라이벌 감정. 지역명이 나와도 그 지역 사람을 비하하지 않으면 통과한다.
- 감탄·강조 관용구: "미쳤다 이 타구", "역대급 경기였다", "말도 안 되는 수비".
- 경기 내용이 아니어도 야구 맥락 안이면 통과: 인터뷰·이적·계약·유니폼·굿즈·직관 후기·
  중계·응원가·구장 이야기.
- 밈·드립·짤·커뮤니티 잡담. 예: "오늘 경기 요약.jpg"
- 짧은 감탄·응원 한 줄: "가자!!", "오늘은 이긴다", "ㅋㅋㅋㅋ".
  짧다는 것은 폐기 근거가 아니다. 길이만 보고 offtopic 으로 판정하지 않는다.
- 사는 쪽·묻는 쪽의 구매 문의와 정보 공유: "굿즈 어디서 사는 게 제일 싸요?".
  spam 은 파는 쪽이 연락·링크로 유도할 때만이다.
- 위에 없더라도, 폐기 근거를 한 줄로 쓸 수 없으면 통과시킨다.

# 출력 형식
반드시 아래 JSON 만 출력한다. 설명·코드펜스·다른 텍스트를 덧붙이지 않는다.
{"results": [{"index": 1, "is_valid": true, "axis": null, "message": ""}]}

- results 의 항목 수는 입력 항목 수와 정확히 같아야 하고, index 는 입력 번호와 1:1로 대응한다.
- is_valid 가 false 일 때만 axis 를 "abuse" | "spam" | "offtopic" 중 하나로 채운다.
- is_valid 가 true 이면 axis 는 null 이고 message 는 빈 문자열로 둔다.
- 폐기일 때 message 는 사람이 읽을 수 있는 한 줄 사유를 한국어로 쓴다(예: "특정 인물 인신공격").
- 정의된 세 값 외의 axis 를 만들어내지 않는다.
- axis 를 정할 때: abuse 조건에 하나라도 걸리면 다른 축과 겹쳐도 무조건 "abuse" 다.
  comment 항목에는 "offtopic" 을 쓰지 않는다.
"""

# unit_kind → 프롬프트에 노출할 라벨.
_UNIT_LABELS = {
    "body": "body(본문)",
    "comment": "comment(댓글)",
}


def build_user_message(items: Sequence[JudgeItem]) -> str:
    """판정 대상 항목들을 번호가 붙은 사용자 메시지로 렌더한다.

    캐시 breakpoint **뒤에** 놓이는 가변부다(PIPE-2SB-65). 게시글 메타(engagement·
    sourceUrl·author 등)는 담지 않는다 — 판정 대상 텍스트와 `unit_kind` 뿐이다
    (PIPE-2SB-45).
    """
    lines = ["다음 {count}개 단위를 각각 독립적으로 판정하라.".format(count=len(items)), ""]
    for index, item in enumerate(items, start=1):
        label = _UNIT_LABELS.get(item.unit_kind, item.unit_kind)
        lines.append("[{index}] unit_kind={label}".format(index=index, label=label))
        lines.append(item.text)
        lines.append("")
    lines.append('결과를 {"results": [...]} JSON 하나로만 출력하라.')
    return "\n".join(lines)


def build_system_blocks(use_cache: bool = True) -> list:
    """Converse API 의 system 블록을 만든다.

    캐시 breakpoint 를 시스템 프롬프트 **뒤**에 둬 접두부가 캐싱되게 한다
    (PIPE-2SB-64/65). 판정 대상 텍스트는 그 뒤 user 메시지로 가므로 프리픽스가
    호출마다 동일하다.
    """
    blocks = [{"text": SYSTEM_PROMPT}]
    if use_cache:
        blocks.append({"cachePoint": {"type": "default"}})
    return blocks
